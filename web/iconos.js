/**
 * Devuelve el markup SVG de un icono.
 * @param {string} nombre  clave de PIXELES
 * @param {number} tamanio lado en pixeles CSS
 */
export function icono(nombre, tamanio = 16) {
    const sprite = PIXELES[nombre];
    if (!sprite) return '';

    const rect = ([x, y], clase) =>
        `<rect x="${x}" y="${y}" width="1" height="1" class="${clase}"/>`;

    const trazo = sprite.a.map((p) => rect(p, 'px-a')).join('');
    const relleno = (sprite.b || []).map((p) => rect(p, 'px-b')).join('');

    // el relleno va primero para que el trazo quede por encima en los solapes
    return `<svg class="icono" width="${tamanio}" height="${tamanio}" viewBox="0 0 16 16" ` +
           `shape-rendering="crispEdges" aria-hidden="true" focusable="false">` +
           `${relleno}${trazo}</svg>`;
}

/** Inserta un icono como nodo, para cuando no queremos innerHTML. */
export function nodoIcono(nombre, tamanio = 16) {
    const contenedor = document.createElement('span');
    contenedor.className = 'icono-caja';
    contenedor.innerHTML = icono(nombre, tamanio);
    return contenedor;
}

